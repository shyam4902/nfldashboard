// Builds design-variants/data.js from the repo's committed data so every
// variant renders the same real numbers. Run from the repo root:
//   node design-variants/build-data.mjs
// Team colours are the production nfl_teams.primary_color values with the
// same high-contrast overrides nfl/index.html applies at load time.
import { readFileSync, writeFileSync } from 'node:fs';

const read = f => JSON.parse(readFileSync(f, 'utf8'));
const schedule = read('schedule.json');
const standings = read('nfl_standings_2026.json');
const stats = read('nfl_stats_2026.json');
const clay = read('clay_projections_2026.json');

const BASE = {
  ARI:'#97233F', ATL:'#A71930', BAL:'#241773', BUF:'#00338D', CAR:'#0085CA', CHI:'#C83200',
  CIN:'#FB4F14', CLE:'#311D00', DAL:'#041E42', DEN:'#FB4F14', DET:'#0076B6', GB:'#203731',
  HOU:'#03202F', IND:'#002C5F', JAX:'#006778', KC:'#E31837', LAC:'#0080C6', LAR:'#003594',
  LV:'#A5ACAF', MIA:'#008E97', MIN:'#4F2683', NE:'#002244', NO:'#D3BC8D', NYG:'#0B2265',
  NYJ:'#125740', PHI:'#004C54', PIT:'#FFB612', SEA:'#002244', SF:'#AA0000', TB:'#D50A0A',
  TEN:'#4B92DB', WAS:'#5A1414',
};
// nfl/index.html TEAM_COLOR_OVERRIDES
const OVERRIDES = {
  NE:'#C60C30', SEA:'#69BE28', HOU:'#A71930', CLE:'#FF3C00', DAL:'#003594', BAL:'#6B3FA0',
  GB:'#187A44', IND:'#00529B', NYG:'#0053A0', NYJ:'#007A53', PHI:'#007A65', WAS:'#8C182A',
};

const teams = {};
for (const t of standings.teams) {
  teams[t.abbr] = {
    abbr: t.abbr, name: t.team, nick: t.team.split(' ').slice(-1)[0],
    city: t.team.split(' ').slice(0, -1).join(' '),
    conf: t.conference, div: t.division,
    color: OVERRIDES[t.abbr] || BASE[t.abbr],
    w: t.wins, l: t.losses, t: t.ties, pct: t.win_pct,
    pf: t.points_for, pa: t.points_against, diff: t.differential,
  };
}
const abbrOf = Object.fromEntries(Object.values(teams).map(t => [t.name, t.abbr]));

const games = schedule.games.map(g => ({
  id: g.game_id, week: g.week, away: abbrOf[g.away_team], home: abbrOf[g.home_team],
  kickoff: g.kickoff_utc, venue: g.venue, tv: g.tv || '',
  final: g.status === 'final', as: g.away_score, hs: g.home_score,
}));

// Clay preseason projected wins (separate model, labelled as such wherever shown).
const clayWins = {};
for (const rows of Object.values(clay.standings.divisions)) {
  for (const r of rows) {
    const a = { ARZ: 'ARI', BLT: 'BAL', CLV: 'CLE', HST: 'HOU' }[r.abbr] || r.abbr;
    if (teams[a]) clayWins[a] = r.wins;
  }
}

const pick = (rows, keys, n = 10) => rows.slice(0, n).map(r => Object.fromEntries(keys.map(k => [k, r[k]])));
const leaders = {
  passing: pick(stats.season_to_date.passing, ['name','team','games','pass_yd','pass_td','pass_int','pass_cmp_pct']),
  rushing: pick(stats.season_to_date.rushing, ['name','team','games','rush_yd','rush_td','rush_att','rush_avg']),
  receiving: pick(stats.season_to_date.receiving, ['name','team','games','rec_yd','rec_td','rec','rec_tgt']),
};

const divisions = standings.divisions.map(d => ({ conf: d.conference, div: d.division, teams: d.teams.map(t => t.abbr) }));

const out = {
  season: schedule.season, week: schedule.week, totalWeeks: schedule.total_weeks,
  generated: schedule.generated, scoresSyncedAt: schedule.scores_synced_at,
  standingsThrough: standings.through_week,
  statsWeeks: stats.completed_weeks,
  clayUpdated: clay.metadata.updated,
  teams, divisions, games, clayWins, leaders,
};
writeFileSync('design-variants/data.js',
  '/* Generated by design-variants/build-data.mjs from schedule.json, nfl_standings_2026.json,\n' +
  '   nfl_stats_2026.json and clay_projections_2026.json. Do not hand-edit. */\n' +
  'window.MB = ' + JSON.stringify(out) + ';\n');
console.log('teams', Object.keys(teams).length, 'games', games.length, 'clay', Object.keys(clayWins).length);
